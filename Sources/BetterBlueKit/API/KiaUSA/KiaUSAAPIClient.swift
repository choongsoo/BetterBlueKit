import CryptoKit
import Foundation

// MARK: - Kia USA API Client

@MainActor
public final class KiaUSAAPIClient: APIClientBase, APIClientProtocol {

    // MARK: - Constants

    /// How long we treat a Kia session ID (`sid`) as valid before forcing
    /// a re-login. Reactive session recovery now handles expired tokens
    /// on-demand, so a longer lifetime prevents proactive churn against
    /// Kia's anti-bot/MFA rate limits.
    static let loginTokenLifetime: TimeInterval = 7 * 86400

    var baseURL: String {
        region.apiBaseURL(for: .kia)
    }

    var apiURL: String {
        "\(baseURL)/apigw/v1/"
    }

    /// Generates a device ID matching the format expected by the Kia Connect US APIGW
    /// (same format generated by the Kia Access / KIAPrimo iOS app).
    public static func generateKiaDeviceId() -> String {
        func randomHex(_ length: Int) -> String {
            (0..<length).map { _ in String(format: "%x", Int.random(in: 0...15)) }.joined()
        }
        return "\(randomHex(22)):\(randomHex(9))_\(randomHex(10))-\(randomHex(5))_\(randomHex(22))_\(randomHex(8))-\(randomHex(18))-_\(randomHex(22))_\(randomHex(17))"
    }

    // Persisted or newly minted device ID matching Kia Connect iOS app format.
    public var deviceId: String

    // Remember-me token cached locally across requests and updated on rotation.
    var rememberMeToken: String?

    // Last valid auth token obtained either through login() or background recovery.
    var activeAuthToken: AuthToken?

    // Client UUID is a UUID5 hash of device_id using DNS namespace
    var clientUUID: String {
        let namespaceUUID = UUID(uuidString: "6ba7b810-9dad-11d1-80b4-00c04fd430c8")!
        return generateUUID5(namespace: namespaceUUID, name: deviceId).uuidString.lowercased()
    }

    public override init(configuration: APIClientConfiguration, urlSession: URLSession = .shared) {
        self.deviceId = configuration.deviceId ?? Self.generateKiaDeviceId()
        self.rememberMeToken = configuration.rememberMeToken
        super.init(configuration: configuration, urlSession: urlSession)
    }

    public override func registerDevice() async throws -> String? {
        let newDeviceId = Self.generateKiaDeviceId()
        self.deviceId = newDeviceId
        configuration = configuration.with(deviceId: newDeviceId)
        return newDeviceId
    }

    public override var apiName: String { "KiaUSA" }

    // MARK: - Headers

    func headers() -> [String: String] {
        let offset = TimeZone.current.secondsFromGMT() / 3600
        let hostName = baseURL.replacingOccurrences(of: "https://", with: "")

        let dateFormatter = DateFormatter()
        dateFormatter.dateFormat = "EEE, dd MMM yyyy HH:mm:ss 'GMT'"
        dateFormatter.locale = Locale(identifier: "en_US_POSIX")
        dateFormatter.timeZone = TimeZone(identifier: "GMT")
        let dateString = dateFormatter.string(from: Date())

        return [
            "content-type": "application/json;charset=utf-8",
            "accept": "application/json, text/plain, */*",
            "accept-encoding": "gzip, deflate, br",
            "accept-language": "en-US,en;q=0.9",
            "accept-charset": "utf-8",
            "appType": "L",
            "appVersion": "7.22.0",
            "clientId": "SPACL716-APL",
            "clientuuid": clientUUID,
            "from": "SPA",
            "host": hostName,
            "language": "0",
            "offset": String(offset),
            "osType": "iOS",
            "osVersion": "15.8.5",
            "phonebrand": "iPhone",
            "secretKey": "sydnat-9kykci-Kuhtep-h5nK",
            "to": "APIGW",
            "tokentype": "A",
            "User-Agent": "KIAPrimo_iOS/37 CFNetwork/1335.0.3.4 Darwin/21.6.0",
            "date": dateString,
            "deviceId": deviceId
        ]
    }

    func authorizedHeaders(authToken: AuthToken, vehicleKey: String? = nil) -> [String: String] {
        var result = headers()
        result["sid"] = authToken.accessToken
        if let key = vehicleKey {
            result["vinkey"] = key
        }
        return result
    }

    // MARK: - APIClientProtocol Implementation

    public func optionalFeaturesSupported() -> [OptionalAPIFeature] {
        [.mfa, .surroundView, .surroundViewCapture]
    }

    public func login() async throws -> AuthToken {
        let token = try await loginWithMFA(sid: nil, rmToken: rememberMeToken ?? configuration.rememberMeToken)
        self.activeAuthToken = token
        configuration.onAuthTokenRefreshed?(token)
        return token
    }

    func loginWithMFA(sid: String?, rmToken: String?) async throws -> AuthToken {
        BBLogger.info(.auth, "KiaUSA: Attempting login for \(username)")

        var loginHeaders = headers()
        if let token = rmToken {
            loginHeaders["rmtoken"] = token
        }
        if let sid {
            loginHeaders["sid"] = sid
        }

        let loginData: [String: Any] = [
            "deviceKey": deviceId,
            "deviceType": 2,
            "tncFlag": 1,
            "userCredential": [
                "userId": username,
                "password": password
            ]
        ]

        let (data, _, response) = try await performJSONRequest(
            url: "\(apiURL)prof/authUser",
            method: .POST,
            headers: loginHeaders,
            body: loginData,
            requestType: .login
        )

        let respHeaders = extractResponseHeaders(from: response)
        let token = try parseLoginResponse(data, headers: respHeaders)
        if let tokenRm = rmToken {
            self.rememberMeToken = tokenRm
        }
        self.activeAuthToken = token
        return token
    }

    public func sendMFACode(xid: String, otpKey: String, method: MFAMethod) async throws {
        BBLogger.info(.mfa, "KiaUSA: Sending OTP via \(method)")

        var otpHeaders = headers()
        otpHeaders["otpkey"] = otpKey
        otpHeaders["notifytype"] = method == .email ? "EMAIL" : "SMS"
        otpHeaders["xid"] = xid

        let (data, _, _) = try await performJSONRequest(
            url: "\(apiURL)cmm/sendOTP",
            method: .POST,
            headers: otpHeaders,
            body: [:],
            requestType: .sendMFA
        )

        try checkForKiaErrors(data: data)
        BBLogger.info(.mfa, "KiaUSA: OTP sent successfully")
    }

    public func verifyMFACode(
        xid: String,
        otpKey: String,
        code: String
    ) async throws -> (rememberMeToken: String, sid: String) {
        BBLogger.info(.mfa, "KiaUSA: Verifying OTP")

        var verifyHeaders = headers()
        verifyHeaders["otpkey"] = otpKey
        verifyHeaders["xid"] = xid

        let (data, _, response) = try await performJSONRequest(
            url: "\(apiURL)cmm/verifyOTP",
            method: .POST,
            headers: verifyHeaders,
            body: ["otp": code],
            requestType: .verifyMFA
        )

        try checkForKiaErrors(data: data)

        let responseHeaders = extractResponseHeaders(from: response)
        guard let rmToken = responseHeaders["rmToken"] ?? responseHeaders["rmtoken"] ?? responseHeaders["RmToken"],
              let sessionId = responseHeaders["sid"] ?? responseHeaders["Sid"] ?? responseHeaders["SID"] else {
            BBLogger.warning(.mfa, "KiaUSA verifyOTP response headers: \(responseHeaders)")
            throw APIError.logError("Verify OTP response missing tokens", apiName: apiName)
        }

        BBLogger.info(.mfa, "KiaUSA OTP verified - rmToken: \(rmToken.prefix(10))..., sid: \(sessionId)")
        return (rmToken, sessionId)
    }

    public func completeMFALogin(sid: String, rmToken: String) async throws -> AuthToken {
        BBLogger.info(.auth, "KiaUSA: Completing MFA login")
        self.rememberMeToken = rmToken
        configuration.onRememberMeTokenRotated?(rmToken)
        let token = try await loginWithMFA(sid: sid, rmToken: rmToken)
        self.activeAuthToken = token
        configuration.onAuthTokenRefreshed?(token)
        return token
    }

    // MARK: - Session Recovery

    /// Runs an API operation with automatic silent re-authentication and retry if the
    /// session token has expired on Kia's servers.
    func withSessionRecovery<T>(
        authToken: AuthToken,
        operation: (AuthToken) async throws -> T
    ) async throws -> T {
        let tokenToUse: AuthToken
        if let active = activeAuthToken, active.accessToken != authToken.accessToken, active.isValid {
            tokenToUse = active
        } else {
            tokenToUse = authToken
        }

        do {
            return try await operation(tokenToUse)
        } catch let error as APIError where error.isSessionExpired {
            guard let rmToken = self.rememberMeToken ?? configuration.rememberMeToken,
                  !rmToken.isEmpty,
                  !username.isEmpty,
                  !password.isEmpty else {
                throw error
            }

            BBLogger.info(.auth, "KiaUSA: Session expired (\(error.message)) — attempting silent re-authentication with rmToken")
            do {
                let refreshedToken = try await login()
                BBLogger.info(.auth, "KiaUSA: Silent re-authentication succeeded, retrying operation")
                return try await operation(refreshedToken)
            } catch let loginError {
                BBLogger.error(.auth, "KiaUSA: Silent re-authentication failed: \(loginError.localizedDescription)")
                // If login failed completely with rmToken, reset deviceId for the next fresh MFA attempt
                self.deviceId = Self.generateKiaDeviceId()
                self.rememberMeToken = nil
                throw error
            }
        }
    }

    public func fetchVehicles(authToken: AuthToken) async throws -> [Vehicle] {
        try await withSessionRecovery(authToken: authToken) { token in
            BBLogger.debug(.api, "KiaUSA: Fetching vehicle list")
            let (data, _) = try await performRequest(
                url: "\(apiURL)ownr/gvl",
                method: .GET,
                headers: authorizedHeaders(authToken: token),
                requestType: .fetchVehicles
            )

            return try parseVehiclesResponse(data)
        }
    }

    public func fetchVehicleStatus(
        for vehicle: Vehicle,
        authToken: AuthToken,
        cached: Bool
    ) async throws -> VehicleStatus {
        try await withSessionRecovery(authToken: authToken) { token in
            let vehicleKeyLog = vehicle.vehicleKey ?? "nil"
            BBLogger.debug(
                .api,
                "KiaUSA: Fetching status for VIN: \(vehicle.vin), vehicleKey: \(vehicleKeyLog), cached: \(cached)"
            )

            // When the caller asks for a real-time reading, hit `rems/rvs` first
            // to make Kia's backend poll the vehicle modem (same endpoint the
            // Kia Access app's pull-to-refresh uses). It's an async server call
            // that blocks until the vehicle responds (20–60 s typical). After
            // it returns we fall through to `cmm/gvi`, which now returns the
            // freshly-refreshed cached snapshot. If the real-time call fails
            // we log and continue — a stale snapshot beats surfacing an error.
            //
            // Cooldown: post-command status polling calls this every ~10–15 s,
            // and back-to-back rvs requests get throttled by Kia (returning
            // errors we'd swallow, i.e. stale snapshots anyway) while each call
            // can block for up to a minute. One successful modem poll per
            // window is enough — within it, `cmm/gvi` already returns the
            // freshly-refreshed snapshot.
            if !cached {
                let now = Date()
                if let last = lastRealTimeRefresh, now.timeIntervalSince(last) < Self.realTimeRefreshCooldown {
                    BBLogger.debug(
                        .api,
                        "KiaUSA: skipping rems/rvs (last real-time refresh \(Int(now.timeIntervalSince(last)))s ago)"
                    )
                } else if try await triggerRealTimeStatusRefresh(for: vehicle, authToken: token) {
                    // Stamp only successful modem polls — a failed/throttled one
                    // should be retried on the next poll, not cooled down.
                    lastRealTimeRefresh = Date()
                }
            }

            // `cmm/gvi` only accepts `vehicleStatus: "1"`. Sending anything else
            // returns the server-side 9001 "Incorrect request payload format".
            let body: [String: Any] = [
                "vehicleConfigReq": [
                    "airTempRange": "0",
                    "maintenance": "1",
                    "seatHeatCoolOption": "0",
                    "vehicle": "1",
                    "vehicleFeature": "0"
                ],
                "vehicleInfoReq": [
                    "drivingActivty": "0",
                    "dtc": "1",
                    "enrollment": "1",
                    "functionalCards": "0",
                    "location": "1",
                    "vehicleStatus": "1",
                    "weather": "0"
                ],
                "vinKey": [vehicle.vehicleKey ?? ""]
            ]

            let (data, _, _) = try await performJSONRequest(
                url: "\(apiURL)cmm/gvi",
                method: .POST,
                headers: authorizedHeaders(authToken: token, vehicleKey: vehicle.vehicleKey),
                body: body,
                requestType: .fetchVehicleStatus,
                vin: vehicle.vin
            )

            return try parseVehicleStatusResponse(data, for: vehicle)
        }
    }

    /// When the last SUCCESSFUL `rems/rvs` modem poll completed.
    private var lastRealTimeRefresh: Date?

    /// Surround-view captures already assembled this session, keyed by
    /// `svmId`.
    ///
    /// Lives here rather than in the `+SurroundView` extension only
    /// because Swift extensions cannot hold stored properties. See
    /// `fetchSurroundViewCaptures` for why it exists: a capture is
    /// immutable once the vehicle has uploaded it, and its imagery is
    /// ~280 KB of base64 behind its own request.
    var surroundViewCache: [String: SurroundViewCapture] = [:]

    /// The last `lbs/svm/inquire` listing, keyed by `svmId`.
    ///
    /// Kept so a capture loaded on demand can still be merged onto the
    /// metadata the index reported, exactly as an eager fetch does.
    /// Metadata only — no imagery — so it costs a few small dictionaries.
    var surroundViewIndex: [String: [String: Any]] = [:]

    public func sendCommand(for vehicle: Vehicle, command: VehicleCommand, authToken: AuthToken) async throws {
        try await withSessionRecovery(authToken: authToken) { token in
            let url = commandURL(for: command)
            let body = commandBody(for: command, vehicle: vehicle)
            let method = commandMethod(for: command)

            let (data, _, _) = try await performJSONRequest(
                url: url,
                method: method,
                headers: authorizedHeaders(authToken: token, vehicleKey: vehicle.vehicleKey),
                body: method == .GET ? nil : body,
                requestType: .sendCommand,
                vin: vehicle.vin
            )

            try checkForKiaErrors(data: data)
        }
    }

    public func fetchEVTripSummary(for vehicle: Vehicle, authToken: AuthToken) async throws -> [EVTripSummary]? {
        // Kia USA doesn't support EV trip details
        nil
    }

    // MARK: - UUID5 Generation

    func generateUUID5(namespace: UUID, name: String) -> UUID {
        let nsUUID = namespace.uuid
        var data = Data([
            nsUUID.0, nsUUID.1, nsUUID.2, nsUUID.3,
            nsUUID.4, nsUUID.5, nsUUID.6, nsUUID.7,
            nsUUID.8, nsUUID.9, nsUUID.10, nsUUID.11,
            nsUUID.12, nsUUID.13, nsUUID.14, nsUUID.15
        ])
        data.append(contentsOf: name.utf8)

        let digest = Insecure.SHA1.hash(data: data)
        var hash = Array(digest)

        hash[6] = (hash[6] & 0x0F) | 0x50  // Version 5
        hash[8] = (hash[8] & 0x3F) | 0x80  // Variant

        return UUID(uuid: (
            hash[0], hash[1], hash[2], hash[3],
            hash[4], hash[5], hash[6], hash[7],
            hash[8], hash[9], hash[10], hash[11],
            hash[12], hash[13], hash[14], hash[15]
        ))
    }
}

// MARK: - Real-time status refresh

extension KiaUSAAPIClient {
    /// Cooldown between successful `rems/rvs` modem polls (see the callsite
    /// comment in `fetchVehicleStatus`).
    static let realTimeRefreshCooldown: TimeInterval = 60

    /// Asks Kia's backend to poll the vehicle's telematics modem for fresh
    /// data. The response comes back once the modem replies — usually within
    /// ~30 seconds. Returns whether the poll succeeded; errors are logged but
    /// swallowed so the caller still gets a (possibly stale) snapshot from
    /// the follow-up `cmm/gvi` call.
    @discardableResult
    func triggerRealTimeStatusRefresh(
        for vehicle: Vehicle,
        authToken: AuthToken
    ) async throws -> Bool {
        BBLogger.info(.api, "KiaUSA: Requesting real-time status refresh for VIN \(vehicle.vin)")

        do {
            let (data, _, _) = try await performJSONRequest(
                url: "\(apiURL)rems/rvs",
                method: .POST,
                headers: authorizedHeaders(authToken: authToken, vehicleKey: vehicle.vehicleKey),
                body: ["requestType": 0],
                requestType: .fetchVehicleStatus,
                vin: vehicle.vin
            )
            try checkForKiaErrors(data: data)
            return true
        } catch let error as APIError where error.isSessionExpired {
            // Bubble auth failures up so withSessionRecovery can refresh the session
            throw error
        } catch {
            // Swallow everything else: the user-visible UX is "refresh took
            // a while and maybe the data is 30 s stale", not a failure.
            BBLogger.warning(.api, "KiaUSA: rems/rvs real-time refresh failed, falling back to cached: \(error)")
            return false
        }
    }
}
